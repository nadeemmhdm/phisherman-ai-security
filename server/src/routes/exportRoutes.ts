import { Router, Request, Response } from 'express';
import { analysisRepo, findingRepo, headerRepo, urlRepo, attachmentRepo } from '../db/database.js';

export const exportRouter = Router();

// Export report as Markdown file
exportRouter.get('/markdown/:analysisId', (req: Request, res: Response) => {
  try {
    const analysisId = String(req.params.analysisId);
    const analysis = analysisRepo.getById(analysisId);
    if (!analysis) {
      return res.status(404).json({ error: 'Analysis not found' });
    }

    const findings = findingRepo.getByAnalysisId(analysisId);
    const urls = urlRepo.getByAnalysisId(analysisId);
    const attachments = attachmentRepo.getByAnalysisId(analysisId);

    let md = `# EMAIL SECURITY INVESTIGATION REPORT\n\n`;
    md += `**Generated By:** PhisherMan Local AI Assistant\n`;
    md += `**Date:** ${new Date(analysis.created_at).toLocaleString()}\n`;
    md += `**Model:** ${analysis.selected_model} (Analysis Mode: ${analysis.analysis_mode.toUpperCase()})\n\n`;
    md += `## Metadata\n`;
    md += `- **Subject:** ${analysis.subject}\n`;
    md += `- **Sender:** ${analysis.sender_email}\n`;
    md += `- **Classification:** ${analysis.classification}\n`;
    md += `- **Confidence:** ${analysis.confidence_level}\n\n`;

    md += `## AI Forensic Report\n\n`;
    md += `${analysis.analysis_result}\n\n`;

    if (findings.length > 0) {
      md += `## Evidence Inventory\n\n`;
      findings.forEach((f, idx) => {
        md += `### ${idx + 1}. ${f.title} (${f.severity?.toUpperCase() || 'MEDIUM'})\n`;
        md += `- **Evidence:** \`${f.evidence}\`\n`;
        md += `- **Security Explanation:** ${f.explanation}\n`;
        md += `- **Recommended Action:** ${f.recommendation}\n\n`;
      });
    }

    if (urls.length > 0) {
      md += `## Extracted Destinations (${urls.length})\n\n`;
      urls.forEach(u => {
        md += `- \`${u.original_url}\` (Host: ${u.hostname})\n`;
      });
      md += `\n`;
    }

    const sanitizedFilename = `phisherman-report-${analysis.id.slice(0, 8)}.md`;
    res.setHeader('Content-Type', 'text/markdown; charset=utf-8');
    res.setHeader('Content-Disposition', `attachment; filename="${sanitizedFilename}"`);
    res.send(md);
  } catch (err: any) {
    res.status(500).json({ error: err.message });
  }
});

